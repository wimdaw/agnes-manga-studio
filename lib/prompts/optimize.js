/**
 * prompts/optimize.js — 脚本增强（8 个单点改造）
 * ------------------------------------------------------------------
 * 设计原则：一次只改一件事。用户点「强化爽点」时，不希望开头、台词、
 * 结构一起被重写——那样改完还得逐句核对哪里变了。
 *
 * 所有优化模板都要求「保留原结构」：原文是 JSON 数组就回 JSON 数组，
 * 是纯文本就回纯文本。否则脚本页拿到一段散文，分镜导入直接失败。
 */
'use strict';

const { block } = require('./ctx');

const FORMAT_RULES = [
  '【输出格式】',
  '1. 保留原文的结构与字段：原文是 JSON 数组就输出同样字段的 JSON 数组；是纯文本就输出纯文本。',
  '2. 保留原文的镜头顺序与数量，除非规则里明确要求增删。',
  '3. 只输出改写后的全文，不要输出修改说明、不要加标题、不要用 Markdown 围栏。',
].join('\n');

const BANS = [
  '【禁止】',
  '1. 禁止新增原文没有的主要角色或场景。',
  '2. 禁止用梦境、失忆、平行时空解释剧情。',
  '3. 禁止把关键信息写成内心独白。',
].join('\n');

function optimizeTemplate({ key, name, order, system, focus, extraBans = [] }) {
  return {
    key,
    name,
    template_type: 'optimize',
    stage: 'optimize',
    order,
    version: 2,
    system,
    content: block(
      '【任务】',
      '对下面的脚本做单点改造：只改规则里要求的部分，其余内容原样保留。',
      '',
      '【原文】',
      '{{脚本内容}}',
      '',
      '【改造规则】',
      ...focus,
      '',
      FORMAT_RULES,
      '',
      BANS,
      ...extraBans,
    ),
    negative_prompt: '',
    notes: `脚本优化 · ${name.replace('强化', '').replace('脚本', '')}`,
    variables: [{ name: '脚本内容', label: '脚本内容', required: true, example: '由页面自动填入当前生成结果' }],
    output_contract: { type: 'text', fields: [] },
  };
}

