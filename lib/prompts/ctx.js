/**
 * prompts/ctx.js — 提示词共享片段
 * ------------------------------------------------------------------
 * 所有模板共用同一套「输出纪律」「竖屏约束」「资产规则」。
 * 写死在各模板里的话，改一条规则要改十几处，迟早漏掉一处，
 * 于是模型在某些步骤守规矩、在另一些步骤又不守。
 */
'use strict';

/** 输出纪律：所有要求 JSON 的模板末尾都拼这段 */
const OUTPUT_DISCIPLINE = [
  '【输出纪律】',
  '1. 只输出 JSON 本身：不要 Markdown 代码围栏、不要前后解释、不要注释。',
  '2. 字符串用双引号，禁止尾逗号，JSON 之外不要有任何字符。',
  '3. 字段一个都不能少：不确定就给空字符串或空数组，不要省略键。',
  '4. 不要出现真实人名、真实品牌、真实影视 IP 的角色名。',
].join('\n');

/** 纯文本输出（图片/视频提示词）的纪律 */
const TEXT_DISCIPLINE = [
  '【输出纪律】',
  '1. 只输出提示词本身，一行，不要引号、不要编号、不要解释。',
  '2. 用英文书写；专有名词和 @资产名 保持原样。',
  '3. 不要输出负面提示词，负面词由程序单独维护。',
].join('\n');

/** 竖屏漫剧的通用硬约束，按需拼进模板 */
const VERTICAL_RULES = [
  '竖屏 9:16：主体居中偏上，重要信息避开画面底部 1/4（会被字幕和进度条遮挡）。',
  '单集内主要场景不超过 5 个、主要角色不超过 6 个，避免大场面群戏。',
  '前 3 秒必须有可见的异常、冲突或反差，不能靠旁白慢慢铺垫。',
].join('\n');

/** 资产一致性规则：所有会产出画面描述的模板都要带 */
const ASSET_RULES = [
  '资产一致性：',
  '1. 角色、场景、道具一律使用资产清单里的名称，并在提示词中写成 @资产名。',
  '2. 同一个资产在不同镜头里不得改名、不得重新描述成另一个人/地方。',
  '3. 资产清单为空时，不要编造 @名称；用通用描述即可。',
].join('\n');

/** 剧本格式规则：单集脚本与分镜共用 */
const SCRIPT_RULES = [
  '台词单句不超过 18 个汉字，旁白单句不超过 25 个汉字（要留出配音时长）。',
  '每个镜头只表达一个信息点；连续三个镜头必须有信息增量，不能重复解释。',
  '禁止用「内心独白」交代关键信息，必须转成可拍的动作或台词。',
].join('\n');

/** 拼接若干片段，自动过滤空值并用空行分隔 */
function block(...parts) {
  return parts.filter(Boolean).join('\n\n');
}

/** 生成 JSON 结构说明块 */
function jsonBlock(lines) {
  return ['【输出 JSON】', ...lines].join('\n');
}

module.exports = {
  OUTPUT_DISCIPLINE,
  TEXT_DISCIPLINE,
  VERTICAL_RULES,
  ASSET_RULES,
  SCRIPT_RULES,
  block,
  jsonBlock,
};
